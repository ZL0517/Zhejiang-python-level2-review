##第16关：血压值
##程序功能：现给出某单位多名职工测量的血压值，输出血压正常的人数。若收缩压在90 - 140之间并且舒张压在60 - 90之间（包含端点值）则称之为正常。
##【输入描述】第一行为一个正整数n，n < 100 其后有n行，每行2个正整数，分别为一名职工测量的收缩压和舒张压，中间以一个空格分隔。
##【输出描述】血压正常的人数。
##【输入样例】4
##100 80
##90 50
##120 60
##140 90
##【输出样例】3

n= int(input())
num = 0
for i in range(n):
    a,b=map(int,input().split())
    if 90<=a<=140 and 60<=b <=90:
        num+=1
print(num)
