##第10关：中奖结果
##程序功能：某活动奖券抽奖的中奖号码公布了，
##奖券号码为4位，三等奖的末位为3，二等奖的末两位为25，一等奖的末三位为618，特等奖是2166。
##请输入任意一个奖券号码，输出中奖结果。
##如：1234为未中奖，3125为二等奖，2166为特等奖。
##【输入描述】一个字符串，表示奖券号码。
##【输出描述】中奖结果：未中奖、三等奖、二等奖、一等奖、特等奖。
##【输入样例】6273
##【输出样例】三等奖

code=input()

if len(code)!=4:
   print("未中奖")
else:
  if code[-1:]=="3":
     print("三等奖")
  elif code[-2:]=="25":
     print("二等奖")
  elif code [-3:] =="618":
     print("一等奖")
  elif code =="2166":
     print("特等奖")
  else:
    print("未中奖")
