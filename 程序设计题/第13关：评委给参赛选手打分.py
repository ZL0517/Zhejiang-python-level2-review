##第13关：评委给参赛选手打分
##程序功能：体操比赛中，评委会给参赛选手打分。选手得分规则为去掉一个最高分和一个最低分，然后计算平均得分，请编程输出某选手的得分。
##【输入描述】第1行包含一个整数n (2<n<100)，表示评委的人数， 第2行包含n个整数，表示n个评委的打分。每个整数之间用空格分隔。
##【输出描述】输出选手的得分，结果保留2位小数。
##【输入样例】4
##100 99 98 97
##【输出样例】98.50

n=int(input())
ls=list(map(int,input().split()))
avg=(sum(ls)-max(ls)-min(ls))/(n-2)
print("{:.2f}".format(avg))
