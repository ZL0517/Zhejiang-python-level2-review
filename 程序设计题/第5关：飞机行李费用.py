##第5关：飞机行李费用
##程序功能：乘坐飞机时，当乘客行李重量不超过10公斤时，可随身携带行李免费。
##当行李重量超过10公斤时，必须办理托运。
##行李费这样计算：如果行李重量大于10公斤且小于等于20公斤时，每公斤2元。
##如果行李重量大于20公斤时，每公斤3元。请编程计算行李费。
##【输入描述】一个正整数（<100），乘客携带行李重量，单位公斤
##【输出描述】一个整数，表示行李费用
##【输入样例】9
##【输出样例】0

weight=int(input())
if weight<=10:
   print(0)
elif 10<weight<=20:
   print(weight*2-20)
else:
   print(weight*3-40)
