##第17关：超市打折后的实付金额
##程序功能：某超市促销规定：购物不超过50元按原金额付款；超过50元不超过150元，按九折付款；超过150元的，按八折付款。输入购物原金额，输出打折后的实付金额。
##【输入格式】一个实数，即购物的原金额。
##【输出格式】一个实数，保留两位小数，表示打折后的实付金额。
##【输入样例】49
##【输出样例】49.00
##【输入样例】60
##【输出样例】54.00

money = eval(input())
if 50 < money <= 150:
    money = money * 0.9
elif money > 150:
    money = money * 0.8
print(f"{money:.2f}")
