##第20题：密码星级
##【程序功能】密码星级的规则是：满足下列任一条件，即加1星，若无一条条件满足，则密码星级为0。(1)含有数字字符；(2)含有小写字母；(3)含有大写字母；(4) 密码长度不小于8。本程序的功能是输入一个字符串密码，输出一个表示密码星级的整数。
##【输入描述】一个字符串，表示密码。
##【输出描述】一个整数，表示密码星级（0-4）。
##【输入样例】abc123ABC
##【输出样例】4

x=input()
a=0
for i in x:
    if i.isdigit():
        a+=1
        break
for i in x:
    if i.islower():
        a+=1
        break
for i in x:
    if i.isupper():
        a+=1
        break
if len(x)>=8:
    a+=1
print(a)
