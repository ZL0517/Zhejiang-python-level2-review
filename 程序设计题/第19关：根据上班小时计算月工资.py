##第19关：根据上班小时计算月工资
##程序功能：某公司每月标准上班时间是120小时，每小时工资是90元, 如果上班时间超出了120小时，超出部分每小时按2倍工资发放（即每小时180元）。请编写程序，输入某员工上班时间，输出月工资。
##【输入格式】1个整数，表示上班时间
##【输出格式】1个整数，表示月工资
##【输入样例】121
##【输出样例】10980

hour = int(input())

if hour <= 120:
    salary = hour *90
else:
    salary = 120*90 +(hour-120)*90*2
print(salary)
