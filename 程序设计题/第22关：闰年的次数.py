##第22关：闰年的次数
##程序功能：凡符合下面两个条件之一的年份是闰年。①能被4整除但不能被100 整除。②能被400整除。编写程序，输入m、n二个年份，统计m和n之间出现闰年的次数并输出。
##【输入描述】m、n二个年份，小的年份先输入，之间用空格分隔。
##【输出描述】闰年的次数。
##【输入样例】2000 2004
##【输出样例】2

m, n = map(int, input().split())
c = 0
for y in range(m, n+1):
    if ((y % 4 == 0) and (y % 100 != 0)) or (y % 400 == 0):
        c += 1
print(c)
