##第31关：涨工资后的金额
##程序功能：公司准备对每位员工涨工资，规则：对于工资小于5000元的，涨50%，其余的增加2500元。编写程序，输入一组工资金额，依次输出涨工资后的金额。
##【输入描述】一行，原来工资金额，之间用空格分隔。
##【输出描述】涨工资后的金额（保留二位小数）。
##【输入样例】3000 4000 6000 2234.59
##【输出样例】4500.00 6000.00 8500.00 3351.89

salary = [eval(x) for x in input().split()]
for i in salary:
     if i < 5000:
         print('{:.2f}'.format(i*1.5), end = ' ')
     else:
         print('{:.2f}'.format(i+2500), end = ' ')
