##第28关：连续编号的3张兑换券
##程序功能：某超市进行促销活动，购买金额超过一定值就随机给一个兑换券，兑换券上有不同的编号，编号是一个1到100之间的数字。当收集到连续编号的三张兑换券时，就可以换一个小礼物。编写一个程序，输入收集到的兑换券编号，输出是否能兑换小礼物。
##【输入描述】一行，多个兑换券编号，之间用空格分隔。
##【输出描述】YES或NO
##【输入样例】16 15 3 6 9 15 17 88
##【输出样例】YES

nums = list(map(int, input().split()))

for x in nums:
    if (x+1 in nums) and (x+2 in nums):
        print('YES')
        break
else:
    print('NO')
