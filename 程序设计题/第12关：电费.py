##第12关：电费
##程序功能：某省电力公司执行“阶梯电价”，居民用户电价分为两个“阶梯”：月用电量50千瓦时（含50千瓦时）以内的，电价为0.53元/千瓦时；超过50千瓦时的，超出部分的用电量，电价上调0.05元/千瓦时。请编写程序计算电费。
##【输入格式】一个非负整数，表示月用电量。
##【输出格式】一个实数，保留两位小数，表示应支付的电费。
##【输入样例】10
##【输出样例】5.30
##【输入样例】60
##【输出样例】32.30

n = int(input())

if n <= 50:
    fee = n*0.53
else:
    fee=50*0.53 +(n-50)*(0.53+0.05)
print(f"{fee:.2f}")
