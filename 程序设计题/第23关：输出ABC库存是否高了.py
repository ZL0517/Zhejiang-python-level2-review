##第23关：输出ABC库存是否高了
##程序功能：某公司仓库只存放ABC三种货物，对应的最高库存为A货物100、B货物200、C货物220。对货物进行盘点后依次输入ABC的实际库存。如有货物的库存大于等于最高库存，则输出货物名称及提示“库存高了”，所有正常则输出“检查正常”。
##【输入描述】一行，以空格隔开，A货物、B货物、C货物的库存。
##【输出描述】分行输出提示信息。
##【输入样例】120 340 120
##【输出样例】A货物库存高了
##B货物库存高了

a, b, c = map(int,input().split())
if (a < 100 ) and (b < 200) and (c < 220):
    print("检查正常")
else:
    if a >= 100:
        print("A货物库存高了")
    if b >= 200:
        print("B货物库存高了")
    if c >= 220:
        print("C货物库存高了")
