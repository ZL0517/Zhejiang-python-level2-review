##第7关：客户评级
##程序功能：某电商要对平台上客户进行评级，按客户的月平均消费金额m进行评级，规则如下：
##m少于2000为1星*，m在 [2000,3000）区间为2星**，m在 [3000,4000）区间为3星***，
##m在 [4000,5000）区间为4星****， m多于5000（包含5000）为5星*****。
##    编写程序，输入月平均消费金额m，输出对应的星数。
##【输入描述】一个大于等于0的消费金额数。
##【输出描述】若干个星号*。
##【输入样例】3600
##【输出样例】***

money = int(input())
if money < 2000:
    print("*")
elif money <3000:
    print("**")
elif money <4000:
    print("***")
elif money < 5000:
    print("****")
else:
    print("*****")

