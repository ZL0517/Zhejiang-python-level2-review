##第15关：水费
##程序功能：为鼓励居民节约用水，自来水公司采取按用水量阶梯式计价的办法，居民应交水费y（元）与月用水量x（吨）相关：当x不超过15吨时，y=4x/3；超过15吨后，y=2.5x-17.5。请编写程序实现水费的计算。
##【输入格式】一个非负整数，表示用水量。
##【输出格式】一个实数，保留两位小数，表示水费。
##【输入样例】12
##【输出样例】16.00
##【输入样例】18
##【输出样例】27.50

x=int(input())

if x <=15:
    print("{:.2f}".format(4*x/3))
else:
    print("{:.2f}".format(2.5*x-17.5))
