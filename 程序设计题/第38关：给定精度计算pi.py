##第38关：给定精度计算pi
##程序功能：π是数学和物理学普遍使用的常数之一，它定义了圆周长与直径之比。但π是一个无理数，即无限不循环小数，π值无法用任何精确公式表示，以下是用格雷戈里公式求π的近似值，π =4-4/3+4/5-4/7+4/9-4/11+... 编写程序，输入精度e，使用该公式求π的近似值，精确到最后一项（指的是上面公式中二个邻近‘+’号和‘-’之间的式子）的绝对值小于e为止。
##【输入描述】一个表示精度要求的小数。
##【输出描述】计算算到的π值。保留5位小数。
##【输入样例】0.001
##【输出样例】3.14209

e = eval(input())
n,pi=1,0
fh=1
while 4/n>=e:
    pi+=4/n*fh
    n+=2
    fh=fh*-1
pi+=4/n*fh
print("{:.5f}".format(pi))
